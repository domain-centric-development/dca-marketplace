"""The rulebook as a person reads it — generated Markdown — or as the views draw it: JSON, each kind's flow drawn in it
as SVG; or one kind's flow alone, as SVG or Mermaid."""

from __future__ import annotations

import json
import typing

from .flow_mermaid import mermaid
from .flow_svg import svg

Model = typing.Dict[str, typing.Any]

ENFORCEMENT = (("gate", "Decided by the gate"), ("runner", "Decided by the runner"),
               ("instructed", "Told to the stages"))
SLOTS = (("gate_before", "gate before"), ("told", "told"), ("gate_after", "gate after"), ("passed", "a pass does"),
         ("decided", "the runner decides"))


#: The keyword each outcome is read after.
SAYS = {"pass": "Passes when", "fail": "Fails when", "skip": "Skips when", "note": "Notes when", "wait": "Waits when",
        "ask": "Asks when"}


def sentence(text: str) -> str:
    text = text.strip()
    return text[:1].upper() + text[1:] + ("" if not text or text[-1] in ".!?)" else ".")


def clause(text: str) -> str:
    text = text.strip()
    return text + ("" if not text or text[-1] in ".!?)" else ".")


def going(goes: typing.List[str]) -> str:
    places = ["stop" if g == "stop" else "once more" if g == "again" else f"back to {g}" for g in goes]
    return f" → {' or '.join(places)}" if places else ""


def rule_lines(rule: Model) -> typing.List[str]:
    title = rule.get("title") or ""
    lines = [f"### {rule['id']}" + (f" — {title}" if title else ""), ""]
    where = ", ".join(rule["stages"]) or "outside the stages"
    kinds = ", ".join(rule["kinds"]) or "every kind"
    lines.append(f"*{rule['part']} · {where} · {kinds}*")
    lines.append("")
    if rule["text"]:
        lines += [f"**Where** {clause(rule['when'])}", "", rule["text"], ""]
    else:
        if rule["why"]:
            lines += [sentence(rule["why"]), ""]
        lines += [f"- **When** {clause(rule['when'])}"]
        lines += [f"- **{SAYS.get(o['state'], o['state'])}** {clause(o['said'])}{going(o.get('goes') or [])}"
                  for o in rule["outcomes"]]
        lines.append("")
        if rule["reports"]:
            lines += [f"**Reports as:** {', '.join(f'`{name}`' for name in rule['reports'])}", ""]
    lines += [f"**Source:** `{rule['source']}`" + (f" · {'placed in' if rule['part'] == 'instruction' else 'bound in'} `{rule['bound']}`"
                                                      if rule.get("bound") else ""), ""]
    return lines


def markdown(view: Model) -> str:
    narrowed = ", ".join(f"{k} {view[k]}" for k in ("stage", "kind") if view.get(k))
    lines = ["# The factory's rules" + (f" — {narrowed}" if narrowed else ""), "",
             "Generated by `factory.sh rules` from the rules' files (`workflow/rules/`, one per rule — the gate's and the "
             "runner's bound by id in the code that checks or decides them, what a stage is told placed by a frame under "
             "`<!-- rule: <id> -->`), and the workflow's stages (`workflow/stages/`, one file per stage, its frame in "
             "it; `workflow/every-stage.md`, what every stage is told). Never edit it: change the rule or the stage "
             "where it is written, its source.", ""]
    rules = {rule["id"]: rule for rule in view["rules"]}
    if view.get("stages"):
        lines += ["## The stages", "", "| Stage | What it is for | Source |", "|---|---|---|"]
        lines += [f"| {s['name']} | {s['about'] or '—'} | {('`' + s['source'] + '`') if s['source'] else '—'} |"
                  for s in view["stages"]]
        lines.append("")
    lines += ["## The flow", ""]
    for kind, flow in view["flow"].items():
        lines += [f"### {kind}", ""]
        if flow["every_gate"]:
            lines += ["Every gate: " + ", ".join(f"`{rule_id}`" for rule_id in flow["every_gate"]), ""]
        steps = flow["steps"]
        lines += ["| Stage | " + " | ".join(label for _k, label in SLOTS) + " |",
                  "|---|" + "---|" * len(SLOTS)]
        for step in steps:
            cells = [", ".join(f"`{rule_id}`" for rule_id in step[key]) or "—" for key, _l in SLOTS]
            lines.append(f"| {step['stage']} | " + " | ".join(cells) + " |")
        lines.append("")
        moves: typing.Dict[typing.Tuple[str, str], typing.List[str]] = {}
        for edge in flow["edges"]:
            if edge["target"] != "stop":
                key = (edge["source"], edge["target"])
                moves.setdefault(key, []).append(f"`{edge['rule']}` {edge['state']}")
        if moves:
            lines += ["Where an outcome sends the story (every other one goes on, or stops the run):", ""]
            lines += [f"- {source} → {target}" + (" (again)" if source == target else "") + ": " + ", ".join(said)
                      for (source, target), said in moves.items()]
            lines.append("")
    if view["outside"]:
        lines += ["Outside the stages — the whole run, every stage alike, the commit hook: "
                  + ", ".join(f"`{rule_id}`" for rule_id in view["outside"]), ""]
    for enforcement, title in ENFORCEMENT:
        chosen = [rule for rule in rules.values() if rule["enforcement"] == enforcement]
        if not chosen:
            continue
        lines += [f"## {title} ({len(chosen)})", ""]
        for rule in chosen:
            lines += rule_lines(rule)
    story = view.get("story")
    if story:
        lines += [f"## Story {story['id']}", "", "What its last gate run per stage reported, by rule; refusals over all its runs.", ""]
        for rule_id, fired in story["fired"].items():
            said = ", ".join(f"{f['stage']} {f['state']}" for f in fired)
            refused = story["refused"].get(rule_id)
            lines.append(f"- `{rule_id}` — {said}" + (f" · refused {refused}×" if refused else ""))
        lines.append("")
    if view["retired"]:
        lines += ["## Retired", ""] + [f"- `{rule['id']}` — {rule['why']}" for rule in view["retired"]] + [""]
    if view["problems"]:
        lines += ["## Problems", ""] + [f"- {problem}" for problem in view["problems"]] + [""]
    if not view["skills"]:
        lines += ["No skills folder found — the rules the stages are told are missing above.", ""]
    return "\n".join(lines).rstrip() + "\n"


def render(view: Model, fmt: str = "md") -> str:
    if fmt in ("svg", "mermaid"):
        kind = view.get("kind") or "story"
        return (svg if fmt == "svg" else mermaid)(view["flow"][kind]["graph"], kind)
    if fmt == "json":
        for kind, flow in view["flow"].items():
            flow["svg"] = svg(flow["graph"], kind)
        return json.dumps(view, indent=2) + "\n"
    return markdown(view)
