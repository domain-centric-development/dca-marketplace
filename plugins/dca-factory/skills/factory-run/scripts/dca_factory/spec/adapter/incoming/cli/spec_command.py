"""`factory-cli.py --spec [--context <c>] [--format md|json]` — what holds: each bounded context with what it is for,
its domain model, its features with their rules and criteria, and the open stories that would change them."""

from __future__ import annotations

import argparse
import json
import os
import sys
import typing

from .....infrastructure import spec as wiring
from ....application.showspec.show_spec import ShowSpecQuery

Model = typing.Dict[str, typing.Any]


def change(context: str, feature: str, rule: str, key: str) -> Model:
    """A wish that becomes a draft story changing one criterion — what it names is written for the backlog skill, the
    person's words follow it."""
    where = f"context `{context}`" + (f", feature `{feature}`" if feature else "") + (f', rule "{rule}"' if rule else "")
    return dict(label="change this", text="What should hold instead?", skill="/factory-backlog", primary=False,
                request=dict(kind="wish", fields={}, words="", open="words", draft=f"spec:{context}:{key}",
                             prefix=f"A change to what holds, asked from the spec: {where}, criterion `{key}`. Write "
                                    f"it as a draft story in that context and feature: the criterion under its key with "
                                    f"its new text, and `## Changed expectations` saying what a person sees now and "
                                    f"after. The change, in the person's words:"))


def addition(context: str, feature: str) -> Model:
    """A wish that becomes a draft story adding a criterion to a feature (a new feature, where `feature` is new)."""
    where = f"context `{context}`" + (f", feature `{feature}`" if feature else "")
    return dict(label="add a scenario", text="What should hold that does not yet?", skill="/factory-backlog",
                primary=False,
                request=dict(kind="wish", fields={}, words="", open="words", draft=f"spec:{context}:{feature}:+",
                             prefix=f"A new criterion for what holds, asked from the spec: {where}. Write it as a "
                                    f"draft story in that context and feature, the criterion under a new key and the "
                                    f"rule it serves. What should hold, in the person's words:"))


def actions(view: Model) -> Model:
    """The view with what a person can ask from it: each criterion a change, each feature an addition."""
    for context in view["contexts"]:
        for feature in context["features"]:
            feature["add"] = addition(context["context"], feature["feature"])
            for rule in feature["rules"]:
                for item in rule["criteria"]:
                    item["change"] = change(context["context"], feature["feature"], rule["rule"], item["key"])
        context["add"] = dict(addition(context["context"], ""), label="add a feature",
                              text="Which feature, and what should hold in it?")
    return view


def markdown(view: Model) -> str:
    lines = ["# What holds", "", "Generated by `factory.sh spec` from the spec (`product/spec/`), the contexts' "
             "glossaries and the designed domain. Never edit it; what holds changes by a story the gate delivers.", ""]
    for context in view["contexts"]:
        lines += [f"## {context['context']}" + (f" — {context['subdomain']}" if context["subdomain"] else ""), ""]
        if context["purpose"]:
            lines += [context["purpose"], ""]
        for group in context["model"]:
            lines.append(f"- **{group['kind']}:** " + ", ".join(t["name"] for t in group["terms"]))
        lines.append("")
        for feature in context["features"]:
            lines += [f"### {feature['feature'] or '(the context itself)'}", ""]
            for rule in feature["rules"]:
                if rule["rule"]:
                    lines += [f"**Rule:** {rule['rule']}", ""]
                for item in rule["criteria"]:
                    changed = ", ".join(f"{c['story']} {c['verdict']}" for c in item["changed_by"])
                    lines.append(f"- `{item['key']}`" + (f" — open: {changed}" if changed else ""))
                lines.append("")
        for story in context["coming"]:
            lines.append(f"- coming with `{story['story']}` ({story['status']}): "
                         + ", ".join(f"`{k['key']}`" for k in story["keys"]))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main(argv: typing.Sequence[str]) -> int:
    parser = argparse.ArgumentParser(prog="factory-cli.py --spec", description="what holds")
    parser.add_argument("--spec", action="store_true", required=True)
    parser.add_argument("--context", help="one context by its folder name")
    parser.add_argument("--format", choices=("md", "json"), default="md")
    args = parser.parse_args(list(argv))
    view = wiring.show_spec(os.getcwd()).execute(ShowSpecQuery(args.context))
    sys.stdout.write(json.dumps(actions(view), indent=2) + "\n" if args.format == "json" else markdown(view))
    return 0
